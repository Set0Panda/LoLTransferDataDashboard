#!/usr/bin/env python3
"""Keep a last-known role and team per player, so a player whose contract row Riot has purged
still lands in the right slot when a headline confirms his signing.

Reads docs/contract/data.js and merges into docs/player-roles.js (never removes entries).
Key: "<region>|<lowercase handle>"  ->  [role, team]. Later snapshots overwrite earlier ones.
Usage: python3 scripts/player_roles.py            (merge the current snapshot)
       python3 scripts/player_roles.py --history  (also replay every earlier commit of data.js)
"""
import json, re, subprocess, sys, unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA, OUT = ROOT / "docs/contract/data.js", ROOT / "docs/player-roles.js"
ROLES = {"TOP", "JUNGLE", "MID", "BOT", "SUPPORT", "COACH"}


def norm(s):
    s = (s or "").lower().replace("ø", "o")
    return "".join(c for c in unicodedata.normalize("NFD", s) if not unicodedata.combining(c))


def rows_of(text):
    teams = json.loads(re.search(r"GCD_TEAMS = (\[.*?\]);", text, re.S).group(1))
    rows = json.loads(re.search(r"GCD_ROWS = (\[.*?\]);", text, re.S).group(1))
    for r in rows:
        t = teams[r[0]]
        if r[2] in ROLES:
            yield f"{t[0]}|{norm(r[1])}", [r[2], t[2]]


def main():
    cur = {}
    if OUT.exists():
        m = re.search(r"=\s*(\{.*\});", OUT.read_text(), re.S)
        if m:
            cur = json.loads(m.group(1))
    snaps = []
    if "--history" in sys.argv:
        shas = subprocess.run(["git", "log", "--reverse", "--format=%H", "--", "docs/contract/data.js"], cwd=ROOT, capture_output=True, text=True).stdout.split()
        for sha in shas:
            snaps.append(subprocess.run(["git", "show", f"{sha}:docs/contract/data.js"], cwd=ROOT, capture_output=True, text=True).stdout)
    snaps.append(DATA.read_text())
    xr = ROOT / "docs/contract/roles-kr.js"          # KR's sheet has no roles; Contract Radar keeps them by hand as "Team|Handle": ROLE
    if xr.exists():
        for k, role in json.loads(re.search(r"=\s*(\{.*\});?", xr.read_text(), re.S).group(1)).items():
            team, _, name = k.rpartition("|")
            if role in ROLES:
                cur[f"KR|{norm(name)}"] = [role, team]
    for text in snaps:
        try:
            for k, v in rows_of(text):
                cur[k] = v
        except Exception:
            pass
    OUT.write_text("// Last-known role and team per player (region|handle), merged from every contract snapshot. Generated by scripts/player_roles.py; never edit by hand.\nwindow.PLAYER_ROLES = " + json.dumps(cur, ensure_ascii=False, separators=(",", ":"), sort_keys=True) + ";\n")
    print(len(cur), "players")


main()
